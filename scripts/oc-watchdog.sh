#!/usr/bin/env bash
# Overclock safety net.
#
# Runs once at boot. If the previous boot did not reach the "boot finished"
# marker within the watchdog window, the script assumes the top OPP is unstable
# on this particular unit and permanently caps the CPU at the vendor validated
# 1.4016 GHz tier.
#
# Why this exists: MSM8916 parts vary a lot. The 2 GHz tier needs 1.35 V at the
# PMIC ceiling, which not every sample tolerates, especially warm. Rather than
# leaving a stick that bootloops, the first failed boot drops it to a known good
# frequency and logs why.
set -euo pipefail

STATE_DIR=/var/lib/oc-watchdog
MARKER=$STATE_DIR/boot-ok
FAILS=$STATE_DIR/failures
CAP_FILE=/etc/systemd/system/oc-watchdog-cap.conf
MAX_FAILS=2
VALIDATED_KHZ=1401600

mkdir -p "$STATE_DIR"

log() { printf 'oc-watchdog: %s\n' "$*" | systemd-cat -t oc-watchdog 2>/dev/null || printf 'oc-watchdog: %s\n' "$*"; }

if [[ -f $MARKER ]]; then
	# Previous boot made it all the way through; nothing to do.
	log "previous boot completed, leaving clock configuration alone"
	exit 0
fi

fails=0
[[ -f $FAILS ]] && fails=$(cat "$FAILS" 2>/dev/null || echo 0)
fails=$(( fails + 1 ))
echo "$fails" > "$FAILS"
log "previous boot did not complete (failure $fails of $MAX_FAILS)"

# This boot counts as good once the script has run this far.
touch "$MARKER"

if (( fails >= MAX_FAILS )); then
	log "unstable at the overclocked tier, capping at ${VALIDATED_KHZ} kHz"
	cat > "$CAP_FILE" <<CONF
# Generated by oc-watchdog after $fails failed boots.
[Service]
ExecStartPre=/bin/sh -c 'for p in /sys/devices/system/cpu/cpu*/cpufreq/scaling_max_freq; do echo $VALIDATED_KHZ > "\$p" 2>/dev/null || true; done'
CONF
	systemctl daemon-reload 2>/dev/null || true
	# Apply immediately as well, in case the unit already ran this boot.
	for p in /sys/devices/system/cpu/cpu*/cpufreq/scaling_max_freq; do
		[[ -w $p ]] && echo "$VALIDATED_KHZ" > "$p" 2>/dev/null || true
	done
fi
